#pragma once

#include <string>

namespace config
{
// Файл настроек вида «имя=значение», совместимый с EnvironmentFile systemd:
// одна пара на строку, комментарии начинаются с #, подстановка значений и
// команды оболочки не поддерживаются.
class DotEnv
{
  public:
    // Читает файл и переносит значения в окружение процесса. Отсутствующий
    // файл ошибкой не считается. Значения, уже заданные в окружении, остаются
    // нетронутыми.
    static void load(const std::string& path);

    // Явно указанный путь, иначе .env в текущем каталоге, рядом с исполняемым
    // файлом или в системном каталоге настроек. Пустая строка — файл не
    // найден.
    static std::string resolvePath(const std::string& explicitPath);
};
} // namespace config